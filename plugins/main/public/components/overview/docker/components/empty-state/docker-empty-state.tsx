import React from 'react';
import { EuiLoadingSpinner } from '@elastic/eui';
import { i18n } from '@osd/i18n';
import { useSelector } from 'react-redux';
import {
  ModuleEmptyState,
  ModuleEmptyStateList,
  unpinPinnedAgent,
} from '../../../../common/no-results/module-empty-state';
import { getSearchOrTimeRangeHint } from '../../../../common/no-results/module-empty-state-texts';
import { DOCS_PATHS } from '../../../../../../common/services/docs-paths';
import {
  DockerDataStatus,
  useDockerDataEverReceived,
} from './use-docker-data-ever-received';
import { DockerListener, useDockerListener } from './use-docker-listener';
import {
  RulesetManagementLink,
  useRulesetManagementApplication,
} from './ruleset-management-link';

interface DockerEmptyStateProps {
  /** Whether any Docker finding has ever reached the indexer. */
  dataStatus: DockerDataStatus;
  /** Pinned agent, an empty object when no agent is pinned. */
  agent?: { id?: string; name?: string };
  /** Unpins the agent so the tab shows all agents. */
  onUnpinAgent: () => void;
}

const getListenerMessage = (
  status: Exclude<DockerListener['status'], 'loading'>,
) => {
  switch (status) {
    case 'enabled':
      return i18n.translate('wazuh.docker.emptyState.listenerEnabled', {
        defaultMessage: 'The Docker listener is enabled on this endpoint.',
      });
    case 'disabled':
      return i18n.translate('wazuh.docker.emptyState.listenerDisabled', {
        defaultMessage: 'The Docker listener is disabled on this endpoint.',
      });
    case 'not-configured':
      return i18n.translate('wazuh.docker.emptyState.listenerNotConfigured', {
        defaultMessage:
          'This endpoint has no Docker listener in its configuration.',
      });
    case 'not-reported':
      return i18n.translate('wazuh.docker.emptyState.notReported', {
        defaultMessage: "This endpoint hasn't reported its configuration yet.",
      });
    default:
      return i18n.translate('wazuh.docker.emptyState.loadError', {
        defaultMessage:
          "The configuration of this endpoint couldn't be loaded.",
      });
  }
};

const EndpointListener = ({ listener }: { listener: DockerListener }) =>
  listener.status === 'loading' ? (
    <>
      <EuiLoadingSpinner size='s' />{' '}
      {i18n.translate('wazuh.docker.emptyState.loadingListener', {
        defaultMessage: 'Checking the Docker listener of this endpoint',
      })}
    </>
  ) : (
    <>{getListenerMessage(listener.status)}</>
  );

const getPageIntro = () =>
  i18n.translate('wazuh.docker.emptyState.setUpIntro', {
    defaultMessage:
      'This page shows the findings generated by the activity of Docker containers.',
  });

const getEnableIntegrationStep = () =>
  i18n.translate('wazuh.docker.emptyState.enableIntegration', {
    defaultMessage:
      'Check that the docker integration is enabled, or that another integration generates Docker findings.',
  });

const SetUpSteps = () => (
  <>
    <p>
      {i18n.translate('wazuh.docker.emptyState.setUpStepsIntro', {
        defaultMessage:
          'No Docker findings have been received yet. To start monitoring:',
      })}
    </p>
    <ModuleEmptyStateList
      ordered
      data-test-subj='wzDockerEmptyStateSteps'
      items={[
        i18n.translate('wazuh.docker.emptyState.enableListener', {
          defaultMessage:
            'Enable the Docker listener on the agent of the Docker host.',
        }),
        getEnableIntegrationStep(),
      ]}
    />
  </>
);

/** The listener of the pinned agent is on: only the integration can be missing. */
const AwaitingFindings = () => (
  <>
    <p>{getPageIntro()}</p>
    <p>{getEnableIntegrationStep()}</p>
  </>
);

/**
 * Shown instead of the default no results callout of the Docker tabs, with the same layout. When
 * no Docker finding has ever arrived it explains what to enable and links the guide; otherwise it
 * keeps the usual hint about the search. For a pinned agent it also says whether the Docker
 * listener is enabled, and offers to unpin the agent.
 */
export const DockerEmptyStateView = ({
  dataStatus,
  agent,
  onUnpinAgent,
}: DockerEmptyStateProps) => {
  const agentId = agent?.id;
  const listener = useDockerListener(agentId);
  const rulesetManagement = useRulesetManagementApplication();
  const notSetUp = dataStatus === 'never-received';
  /* The listener of the pinned agent is already on, so the first set-up step is done. */
  const awaitingFindings = notSetUp && listener?.status === 'enabled';

  return (
    <ModuleEmptyState
      testSubj='Docker'
      title={
        awaitingFindings
          ? i18n.translate('wazuh.docker.emptyState.waitingTitle', {
              defaultMessage: "Docker findings haven't arrived yet",
            })
          : notSetUp
          ? i18n.translate('wazuh.docker.emptyState.setUpTitle', {
              defaultMessage: "Docker monitoring isn't set up yet",
            })
          : i18n.translate('wazuh.docker.emptyState.title', {
              defaultMessage: 'No Docker findings found',
            })
      }
      onUnpinAgent={agentId ? onUnpinAgent : undefined}
      actions={
        notSetUp && rulesetManagement
          ? [
              <RulesetManagementLink
                key='ruleset-management'
                application={rulesetManagement}
              />,
            ]
          : []
      }
      docs={{
        path: DOCS_PATHS.docker,
        label: i18n.translate('wazuh.docker.emptyState.guideLink', {
          defaultMessage: 'How to monitor Docker environments',
        }),
        testSubj: 'wzDockerEmptyStateGuide',
      }}
      hint={
        awaitingFindings
          ? i18n.translate('wazuh.docker.emptyState.listenerEnabledSetUp', {
              defaultMessage:
                'The Docker listener is enabled on this endpoint, but no Docker findings have been received yet.',
            })
          : notSetUp
          ? getPageIntro()
          : getSearchOrTimeRangeHint()
      }
    >
      {awaitingFindings ? (
        <AwaitingFindings />
      ) : notSetUp ? (
        <SetUpSteps />
      ) : null}
      {listener && !awaitingFindings && (
        <p>
          <EndpointListener listener={listener} />
        </p>
      )}
    </ModuleEmptyState>
  );
};

interface PinnedAgentState {
  appStateReducers?: { currentAgentData?: { id?: string; name?: string } };
}

/** Empty state of the Docker tabs for the pinned agent, if any. */
export const DockerEmptyState = () => {
  const agent = useSelector(
    (state: PinnedAgentState) => state.appStateReducers?.currentAgentData,
  );
  const dataStatus = useDockerDataEverReceived();

  return (
    <DockerEmptyStateView
      dataStatus={dataStatus}
      agent={agent}
      onUnpinAgent={unpinPinnedAgent}
    />
  );
};
